export const DEFAULT_COUNTRY: CountryItem = COUNTRIES[0]; // السعودية

export function normalizeSearch(str: string): string {
  return str
    .toLowerCase()
    .trim()
    .replace(/[أإآ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .replace(/[\u064B-\u065F]/g, ""); // Remove Arabic diacritics
}

export function searchCountries(query: string): CountryItem[] {
  const q = normalizeSearch(query);
  if (!q) return COUNTRIES;

  // Check if query is digits or starts with +
  const cleanDigits = q.replace(/^\+/, "");

  return COUNTRIES.filter((c) => {
    const matchAr = normalizeSearch(c.nameAr).includes(q);
    const matchEn = c.nameEn.toLowerCase().includes(q);
    const matchNat = normalizeSearch(c.nationalityAr).includes(q);
    const matchCode = c.code.toLowerCase().includes(q);
    const dialDigits = c.dialCode.replace(/^\+/, "");
    const matchDial =
      c.dialCode.includes(q) ||
      dialDigits.includes(cleanDigits) ||
      c.dialCode.includes("+" + cleanDigits);

    return matchAr || matchEn || matchNat || matchCode || matchDial;
  });
}
